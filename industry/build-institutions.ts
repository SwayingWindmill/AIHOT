// Writes industry/institutions.ts, the institution directory the taxonomy builds its entities from.
// Ids are ZhiPanda's institution slugs, so a subject id here and an institution in ZhiPanda's API agree.
//
//   node industry/build-institutions.ts --zhipanda <path to the ZhiPanda repo>
//
// Reads <repo>/data/curation/institutions/institutions.json (ZhiPanda's canonical institutions) and
// industry/institutions-extra.json (aliases and domains, plus institutions ZhiPanda has no slug for yet).
// Then reports what the directory misses: official accounts in <repo>/data/collector/targets.yaml, and
// panda locations in <repo>/data/curation/pandas/pandas.csv that three or more pandas share.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";

interface Canonical { slug: string; nameZh: string; nameEn: string; countryCode: string; profile?: { websiteUrl?: string } }
interface Extra { slug: string; nameZh?: string; nameEn?: string; countryCode?: string; aliases: string[]; domains: string[] }
interface Institution { id: string; nameZh: string; nameEn: string; countryCode: string; zhipanda: boolean; aliases: string[]; domains: string[] }

const { values } = parseArgs({ options: { zhipanda: { type: "string" } } });
if (!values.zhipanda) {
  console.error("usage: node industry/build-institutions.ts --zhipanda <path to the ZhiPanda repo>");
  process.exit(2);
}
const repo = path.resolve(values.zhipanda);
const here = import.meta.dirname;

const canonical = (JSON.parse(readFileSync(path.join(repo, "data/curation/institutions/institutions.json"), "utf8")) as { institutions: Canonical[] }).institutions;
const extras = (JSON.parse(readFileSync(path.join(here, "institutions-extra.json"), "utf8")) as { institutions: Extra[] }).institutions;

const problems: string[] = [];
const extraBySlug = new Map(extras.map((e) => [e.slug, e]));
const hostOf = (url: string | undefined) => (url ? new URL(url).hostname.replace(/^www\./, "") : null);
const unique = (names: string[]) => [...new Set(names.map((n) => n.trim()).filter(Boolean))];

const institutions: Institution[] = canonical.map((c) => {
  const extra = extraBySlug.get(c.slug);
  const host = hostOf(c.profile?.websiteUrl);
  return {
    id: c.slug, nameZh: c.nameZh, nameEn: c.nameEn, countryCode: c.countryCode, zhipanda: true,
    aliases: unique([c.nameZh, ...(extra?.aliases ?? []), c.nameEn]),
    domains: unique([...(host ? [host] : []), ...(extra?.domains ?? [])]),
  };
});
const canonicalSlugs = new Set(canonical.map((c) => c.slug));
for (const e of extras) {
  if (canonicalSlugs.has(e.slug)) continue;
  if (!e.nameZh || !e.nameEn || !e.countryCode) {
    problems.push(`${e.slug}: not in ZhiPanda, so it needs nameZh, nameEn and countryCode`);
    continue;
  }
  institutions.push({
    id: e.slug, nameZh: e.nameZh, nameEn: e.nameEn, countryCode: e.countryCode, zhipanda: false,
    aliases: unique([e.nameZh, ...e.aliases, e.nameEn]), domains: unique(e.domains),
  });
}

const owner = new Map<string, string>();
for (const i of institutions) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(i.id)) problems.push(`${i.id}: a slug is lowercase words joined by hyphens`);
  for (const alias of i.aliases) {
    const key = alias.toLowerCase();
    const other = owner.get(key);
    if (other && other !== i.id) problems.push(`"${alias}" names both ${other} and ${i.id}`);
    owner.set(key, i.id);
  }
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const out = path.join(here, "institutions.ts");
writeFileSync(out, `// Generated by industry/build-institutions.ts from ZhiPanda's data/curation/institutions/institutions.json
// and industry/institutions-extra.json. Do not edit: change the inputs and run the script again.
// zhipanda: false marks an institution ZhiPanda has no slug for yet; its id is a proposal.

export interface Institution {
  id: string;
  nameZh: string;
  nameEn: string;
  countryCode: string;
  zhipanda: boolean;
  aliases: readonly string[];
  domains: readonly string[];
}

export const INSTITUTIONS: readonly Institution[] = [
${institutions.map((i) => `  ${JSON.stringify(i)},`).join("\n")}
];
`);

const named = (text: string) => institutions.find((i) => i.aliases.some((a) => text.toLowerCase().includes(a.toLowerCase())))?.id ?? null;

const targets = readFileSync(path.join(repo, "data/collector/targets.yaml"), "utf8");
const officialLabels = [...targets.matchAll(/^\s*label:\s*(.+?)\s*\n\s*tier:\s*official\b/gm)].map((m) => m[1]!.replace(/（(?:微博|抖音|小红书)）$/, ""));
const unmatchedAccounts = unique(officialLabels).filter((l) => !named(l));

const locations = new Map<string, number>();
for (const row of csvRows(readFileSync(path.join(repo, "data/curation/pandas/pandas.csv"), "utf8").replace(/^﻿/, ""))) {
  const location = row.current_location?.trim();
  if (location) locations.set(location, (locations.get(location) ?? 0) + 1);
}
const unmatchedLocations = [...locations].filter(([l, n]) => n >= 3 && !named(l)).sort((a, b) => b[1] - a[1]);

const aliasCount = institutions.reduce((n, i) => n + i.aliases.length, 0);
console.log(`${path.relative(process.cwd(), out)}: ${institutions.length} institutions (${institutions.filter((i) => i.zhipanda).length} ZhiPanda slugs), ${aliasCount} names`);
console.log(`official accounts in targets.yaml no institution names (${unmatchedAccounts.length}): ${unmatchedAccounts.join("、") || "none"}`);
console.log(`locations of three or more pandas no institution names (${unmatchedLocations.length}):`);
for (const [l, n] of unmatchedLocations) console.log(`  ${n}  ${l}`);

/** RFC 4180 rows as header-keyed records: quoted fields may hold commas, quotes and newlines. */
function csvRows(text: string): Array<Record<string, string>> {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]!;
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; } else if (ch === '"') quoted = false; else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows;
  return body.filter((r) => r.length > 1).map((r) => Object.fromEntries(header!.map((h, k) => [h, r[k] ?? ""])));
}
